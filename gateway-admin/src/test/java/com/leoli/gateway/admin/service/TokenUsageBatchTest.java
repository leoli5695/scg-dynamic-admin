package com.leoli.gateway.admin.service;

import com.fasterxml.jackson.databind.ObjectMapper;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.transaction.support.TransactionTemplate;
import java.util.*;
import static org.junit.jupiter.api.Assertions.*;

class TokenUsageBatchTest {
    private JdbcTemplate jdbc;
    private TokenQuotaService service;
    private TransactionTemplate tx;
    @BeforeEach void setup() {
        var source = new DriverManagerDataSource("jdbc:h2:mem:usage-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", "");
        jdbc = new JdbcTemplate(source); tx = new TransactionTemplate(new DataSourceTransactionManager(source));
        service = new TokenQuotaService(null, null, null, null, null, new ObjectMapper(), null);
        ReflectionTestUtils.setField(service, "usageJdbc", jdbc);
        jdbc.execute("""
                CREATE TABLE token_usage_history (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                tenant_id VARCHAR(64) NOT NULL, trace_id VARCHAR(64) UNIQUE, route_id VARCHAR(64),model VARCHAR(64),
                prompt_tokens INTEGER,completion_tokens INTEGER,total_tokens INTEGER,instance_id VARCHAR(64),
                response_format VARCHAR(20),latency_ms BIGINT,request_time TIMESTAMP NOT NULL,created_at TIMESTAMP NOT NULL)
                """);
        new org.springframework.jdbc.datasource.init.ResourceDatabasePopulator(
                new org.springframework.core.io.ClassPathResource("sql/alter-token-usage-outcome.sql"),
                new org.springframework.core.io.ClassPathResource("sql/alter-token-usage-event-id.sql"),
                new org.springframework.core.io.ClassPathResource("sql/alter-token-usage-reconciliation.sql")).execute(source);
    }
    @Test void recordsNumbersUnicodeAndLifecycleFields() {
        tx.executeWithoutResult(status -> service.recordTokenUsageBatch(List.of(Map.of("tenantId", "租户", "traceId", "one",
                "totalTokens", 12L, "latencyMs", 15, "requestTime", "2026-10-28T12:00:00"), Map.of("tenantId", "second"))));
        var row = jdbc.queryForMap("SELECT * FROM token_usage_history WHERE trace_id='one'");
        assertEquals("租户", row.get("TENANT_ID")); assertEquals(12, row.get("TOTAL_TOKENS"));
        assertEquals(0, row.get("PROMPT_TOKENS")); assertEquals(15L, row.get("LATENCY_MS"));
        assertEquals(java.sql.Timestamp.valueOf("2026-10-28 12:00:00"), row.get("REQUEST_TIME"));
        assertNotNull(row.get("CREATED_AT")); assertEquals(2, jdbc.queryForObject("SELECT COUNT(*) FROM token_usage_history", Integer.class));
    }
    @Test void jdbcFailureRollsBackEntireBatch() {
        assertThrows(org.springframework.dao.DataIntegrityViolationException.class, () -> tx.executeWithoutResult(status ->
                service.recordTokenUsageBatch(List.of(Map.of("tenantId", "t", "traceId", "dup"), Map.of("tenantId", "t", "traceId", "dup")))));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM token_usage_history", Integer.class));
    }
    @Test void preservesUnknownAndFailedSettlementStates() {
        var row = new HashMap<String, Object>();
        row.put("tenantId", "tenant"); row.put("usageStatus", "UNKNOWN");
        row.put("settlementStatus", "PENDING"); row.put("reservedTokens", 100L);
        row.put("provider", "openai"); row.put("serviceId", "channel-a"); row.put("totalTokens", null);
        row.put("quotaMonth", "202609"); row.put("quotaDay", "20260930"); row.put("quotaPeriod", "BOTH");
        tx.executeWithoutResult(status -> service.recordTokenUsageBatch(List.of(row)));
        var stored = jdbc.queryForMap("SELECT * FROM token_usage_history");
        assertEquals("UNKNOWN", stored.get("USAGE_STATUS"));
        assertEquals("PENDING", stored.get("SETTLEMENT_STATUS"));
        assertNull(stored.get("CHARGED_TOKENS"));
        assertEquals(100L, stored.get("RESERVED_TOKENS"));
        assertEquals("channel-a", stored.get("SERVICE_ID"));
        assertEquals("20260930", stored.get("QUOTA_DAY"));
        assertEquals("202609", stored.get("QUOTA_MONTH"));
        assertEquals("BOTH", stored.get("QUOTA_PERIOD"));
    }
    @Test void validatesBatchBeforeWriting() {
        assertThrows(IllegalArgumentException.class, () -> service.recordTokenUsageBatch(List.of(Map.of("tenantId", "t"), Map.of())));
        assertThrows(IllegalArgumentException.class, () -> service.recordTokenUsageBatch(Collections.nCopies(33, Map.of("tenantId", "t"))));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM token_usage_history", Integer.class));
    }
    @Test void replayAndDuplicateWithinBatchAreRecordedOnce() {
        var event = Map.<String, Object>of("tenantId", "t", "eventId", UUID.randomUUID().toString(), "totalTokens", 12);
        tx.executeWithoutResult(status -> service.recordTokenUsageBatch(List.of(event, event)));
        tx.executeWithoutResult(status -> service.recordTokenUsageBatch(List.of(event)));
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM token_usage_history", Integer.class));
        assertEquals(12, jdbc.queryForObject("SELECT SUM(total_tokens) FROM token_usage_history", Integer.class));
    }
    @Test void mixedLegacyAndReplayRecordsDoNotDuplicateLegacyRowsDuringRecovery() {
        var event = Map.<String, Object>of("tenantId", "t", "eventId", "event-one");
        tx.executeWithoutResult(status -> service.recordTokenUsageBatch(List.of(event)));
        tx.executeWithoutResult(status -> service.recordTokenUsageBatch(List.of(Map.of("tenantId", "legacy"), event,
                Map.of("tenantId", "t", "eventId", "event-two"))));
        assertEquals(3, jdbc.queryForObject("SELECT COUNT(*) FROM token_usage_history", Integer.class));
    }
    @Test void unrelatedUniqueConstraintStillRollsBackReplayableBatch() {
        assertThrows(org.springframework.dao.DataIntegrityViolationException.class, () -> tx.executeWithoutResult(status ->
                service.recordTokenUsageBatch(List.of(Map.of("tenantId", "t", "eventId", "one", "traceId", "dup"),
                        Map.of("tenantId", "t", "eventId", "two", "traceId", "dup")))));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM token_usage_history", Integer.class));
    }
    @Test void concurrentDeliveryOfSameEventIsIdempotent() throws Exception {
        var event = Map.<String, Object>of("tenantId", "t", "eventId", "concurrent-event", "totalTokens", 12);
        var ready = new java.util.concurrent.CountDownLatch(2);
        try (var workers = java.util.concurrent.Executors.newFixedThreadPool(2)) {
            java.util.concurrent.Callable<Void> deliver = () -> {
                ready.countDown(); assertTrue(ready.await(5, java.util.concurrent.TimeUnit.SECONDS));
                tx.executeWithoutResult(status -> service.recordTokenUsageBatch(List.of(event)));
                return null;
            };
            var first = workers.submit(deliver); var second = workers.submit(deliver);
            first.get(10, java.util.concurrent.TimeUnit.SECONDS); second.get(10, java.util.concurrent.TimeUnit.SECONDS);
        }
        assertEquals(1, jdbc.queryForObject("SELECT COUNT(*) FROM token_usage_history", Integer.class));
    }
}
