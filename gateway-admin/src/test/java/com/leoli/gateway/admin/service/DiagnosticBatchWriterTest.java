package com.leoli.gateway.admin.service;

import com.leoli.gateway.admin.model.FilterChainExecution;
import com.leoli.gateway.admin.model.RequestTrace;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.support.TransactionTemplate;

import java.time.LocalDateTime;
import java.util.List;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

class DiagnosticBatchWriterTest {
    private JdbcTemplate jdbc;
    private DiagnosticBatchWriter writer;
    private TransactionTemplate transactions;

    @BeforeEach void setup() {
        var source = new DriverManagerDataSource("jdbc:h2:mem:diagnostics-" + UUID.randomUUID()
                + ";DB_CLOSE_DELAY=-1;MODE=MySQL", "sa", "");
        jdbc = new JdbcTemplate(source);
        transactions = new TransactionTemplate(new DataSourceTransactionManager(source));
        writer = new DiagnosticBatchWriter(jdbc);
        jdbc.execute("""
                CREATE TABLE request_trace (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                instance_id VARCHAR(36),trace_id VARCHAR(36) UNIQUE,route_id VARCHAR(100),method VARCHAR(10),
                uri VARCHAR(2000),path VARCHAR(500),query_string VARCHAR(1000),request_headers TEXT,
                request_body TEXT,status_code INTEGER,response_headers TEXT,response_body TEXT,
                target_instance VARCHAR(255),latency_ms BIGINT,error_message TEXT,error_type VARCHAR(50),
                client_ip VARCHAR(50),user_agent VARCHAR(500),trace_type VARCHAR(20),replayable BOOLEAN,
                replay_type VARCHAR(20),replay_count INTEGER,last_replay_result TEXT,trace_time TIMESTAMP,
                created_at TIMESTAMP NOT NULL)
                """);
        jdbc.execute("""
                CREATE TABLE filter_chain_execution (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                trace_id VARCHAR(64) NOT NULL,filter_name VARCHAR(100) NOT NULL,filter_order INTEGER NOT NULL,
                duration_ms BIGINT NOT NULL,duration_micros BIGINT NOT NULL,self_time_ms BIGINT,
                self_time_micros BIGINT,success BOOLEAN NOT NULL,error_message TEXT,time_percentage DOUBLE,
                instance_id VARCHAR(36),created_at TIMESTAMP NOT NULL)
                """);
    }

    @Test void writesCompleteTraceFieldsAndLifecycleDefaultsInOneBatch() {
        var first = trace("first");
        first.setRequestHeaders("{\"Accept\":\"application/json\"}");
        first.setResponseHeaders("{\"Content-Type\":\"application/json\"}");
        first.setRequestBody("中文请求"); first.setResponseBody("中文响应");
        first.setLatencyMs(17L); first.setStatusCode(201);
        first.setTraceTime(LocalDateTime.of(2026, 10, 28, 2, 0));
        int written = transactions.execute(status -> writer.writeTraces(List.of(first, trace("second"))));
        assertEquals(2, written);
        var row = jdbc.queryForMap("SELECT * FROM request_trace WHERE trace_id='first'");
        assertEquals("中文请求", row.get("REQUEST_BODY")); assertEquals("中文响应", row.get("RESPONSE_BODY"));
        assertEquals(201, row.get("STATUS_CODE")); assertEquals(17L, row.get("LATENCY_MS"));
        assertEquals(first.getResponseHeaders(), row.get("RESPONSE_HEADERS"));
        assertEquals(0, row.get("REPLAY_COUNT")); assertEquals(true, row.get("REPLAYABLE"));
        assertEquals("HTTP", row.get("REPLAY_TYPE")); assertNotNull(row.get("CREATED_AT"));
        assertEquals(java.sql.Timestamp.valueOf(first.getTraceTime()), row.get("TRACE_TIME"));
    }

    @Test void batchFailureRollsBackRatherThanLeavingPartialTraceWrites() {
        assertThrows(org.springframework.dao.DataIntegrityViolationException.class,
                () -> transactions.execute(status -> writer.writeTraces(List.of(trace("duplicate"), trace("duplicate")))));
        assertEquals(0, jdbc.queryForObject("SELECT COUNT(*) FROM request_trace", Integer.class));
    }

    @Test void writesFilterPrecisionAndNullableFieldsWithoutPerRowGeneratedKeys() {
        var execution = new FilterChainExecution();
        execution.setTraceId("first"); execution.setFilterName("Authentication"); execution.setFilterOrder(-100);
        execution.setDurationMs(12L); execution.setDurationMicros(12345L);
        execution.setSelfTimeMs(2L); execution.setSelfTimeMicros(2345L);
        execution.setTimePercentage(25.0); execution.setSuccess(false); execution.setErrorMessage("failed");
        execution.setInstanceId("local");
        int written = transactions.execute(status -> writer.writeExecutions(List.of(execution, execution)));
        assertEquals(2, written);
        var rows = jdbc.queryForList("SELECT * FROM filter_chain_execution");
        assertEquals(2, rows.size()); assertNotEquals(rows.get(0).get("ID"), rows.get(1).get("ID"));
        var row = rows.get(0); assertEquals(12345L, row.get("DURATION_MICROS"));
        assertEquals(2345L, row.get("SELF_TIME_MICROS")); assertEquals(false, row.get("SUCCESS"));
        assertEquals(25.0, row.get("TIME_PERCENTAGE")); assertNotNull(row.get("CREATED_AT"));
    }

    private RequestTrace trace(String id) {
        var trace = new RequestTrace(); trace.setTraceId(id); trace.setInstanceId("local");
        trace.setRouteId("route"); trace.setMethod("POST"); trace.setUri("/example?q=1"); trace.setPath("/example");
        return trace;
    }
}
