package com.leoli.gateway.admin.service;

import com.leoli.gateway.admin.entity.TokenUsageHistoryEntity;
import com.leoli.gateway.admin.entity.TokenUsageReconciliationEntity;
import com.leoli.gateway.admin.repository.TokenUsageHistoryRepository;
import org.hibernate.cfg.Configuration;
import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.data.domain.PageRequest;
import org.springframework.data.jpa.repository.support.JpaRepositoryFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.init.ResourceDatabasePopulator;
import java.time.LocalDateTime;
import java.util.UUID;
import static org.junit.jupiter.api.Assertions.*;

class TokenUsageExceptionQueryTest {
    @Test void migratedSchemaSupportsJpaAndUnresolvedFilterExcludesReconciledUsage() {
        String url = "jdbc:h2:mem:usage-query-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1";
        var source = new DriverManagerDataSource(url,"sa","");
        var jdbc = new JdbcTemplate(source);
        jdbc.execute("""
                CREATE TABLE token_usage_history (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                tenant_id VARCHAR(64) NOT NULL,trace_id VARCHAR(64),route_id VARCHAR(64),model VARCHAR(64),
                prompt_tokens INTEGER,completion_tokens INTEGER,total_tokens INTEGER NOT NULL,instance_id VARCHAR(64),
                response_format VARCHAR(20),latency_ms BIGINT,request_time TIMESTAMP NOT NULL,created_at TIMESTAMP)
                """);
        new ResourceDatabasePopulator(new ClassPathResource("sql/alter-token-usage-outcome.sql"),
                new ClassPathResource("sql/alter-token-usage-event-id.sql"),
                new ClassPathResource("sql/alter-token-usage-reconciliation.sql")).execute(source);
        for (String status : new String[]{"UNKNOWN","ESTIMATED","CONFIRMED","RECONCILED"})
            jdbc.update("INSERT INTO token_usage_history (tenant_id,total_tokens,usage_status,settlement_status,request_time) VALUES ('t',0,?,'APPLIED',?)",
                    status,LocalDateTime.of(2026,10,28,12,0));
        jdbc.update("INSERT INTO token_usage_history (tenant_id,total_tokens,usage_status,settlement_status,request_time) VALUES ('t',30,'CONFIRMED','FAILED',?)",
                LocalDateTime.of(2026,10,28,12,0));
        Configuration configuration = new Configuration().addAnnotatedClass(TokenUsageHistoryEntity.class)
                .addAnnotatedClass(TokenUsageReconciliationEntity.class);
        configuration.setProperty("hibernate.connection.url",url);
        configuration.setProperty("hibernate.connection.username","sa");
        configuration.setProperty("hibernate.connection.password","");
        configuration.setProperty("hibernate.hbm2ddl.auto","validate");
        try (var factory = configuration.buildSessionFactory(); var em = factory.createEntityManager()) {
            var repository = new JpaRepositoryFactory(em).getRepository(TokenUsageHistoryRepository.class);
            var from = LocalDateTime.of(2026,10,28,0,0); var to = from.plusDays(1);
            assertEquals(5,repository.events(from,to,null,null,null,null,false,PageRequest.of(0,20)).getTotalElements());
            var unresolved = repository.events(from,to,null,null,null,null,true,PageRequest.of(0,20));
            assertEquals(3,unresolved.getTotalElements());
            assertTrue(unresolved.stream().noneMatch(row -> "RECONCILED".equals(row.getUsageStatus())));
        }
    }
}
