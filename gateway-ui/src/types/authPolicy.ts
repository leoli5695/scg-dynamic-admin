/**
 * Auth policy domain types.
 *
 * Field-aligned with backend sources of truth:
 * - model/AuthPolicyDefinition.java (policy config, stored as JSON)
 * - model/RouteAuthBindingEntity.java (route binding rows)
 * - controller/AuthPolicyController.java (/api/auth)
 */

/** enums/AuthType codes. */
export type AuthType = 'JWT' | 'API_KEY' | 'OAUTH2' | 'BASIC' | 'HMAC';

/**
 * model/AuthPolicyDefinition — both the GET response shape and the
 * create/update request body. All type-specific config fields live at the
 * top level (the entity serializes them from its JSON config column).
 */
export interface AuthPolicyDefinition {
  /** UUID; generated by the backend on create. */
  policyId?: string;
  /** Business identifier; unique per instance on create. */
  policyName: string;
  authType: AuthType;
  enabled?: boolean;
  /** UI-only on the backend (transient, not pushed to Nacos). */
  description?: string;

  // ---- JWT ----
  secretKey?: string;
  jwtIssuer?: string;
  jwtAudience?: string;
  jwtAlgorithm?: string;
  jwtPublicKey?: string;
  /** Backend default 60. */
  jwtClockSkewSeconds?: number;

  // ---- API Key ----
  apiKey?: string;
  /** Backend default "X-API-Key". */
  apiKeyHeader?: string;
  apiKeyQueryParam?: string;
  /** tenantId -> per-key metadata map. */
  apiKeys?: Record<string, Record<string, unknown>>;
  apiKeyPrefix?: string;

  // ---- OAuth2 ----
  clientId?: string;
  clientSecret?: string;
  tokenEndpoint?: string;
  userInfoEndpoint?: string;
  requiredScopes?: string;
  /** Backend default 300. */
  tokenCacheTtlSeconds?: number;

  // ---- Basic ----
  basicUsername?: string;
  basicPassword?: string;
  basicUsers?: Record<string, string>;
  passwordHashAlgorithm?: string;
  realm?: string;

  // ---- HMAC ----
  accessKey?: string;
  accessKeySecrets?: Record<string, string>;
  /** Backend default "HMAC-SHA256". */
  signatureAlgorithm?: string;
  /** Backend default 5. */
  clockSkewMinutes?: number;
  /** Backend default true. */
  requireNonce?: boolean;
  /** Backend default false. */
  validateContentMd5?: boolean;

  // ---- Common ----
  customConfig?: string;
  whitelistPaths?: string[];
  /** Backend default "JSON". */
  errorResponseFormat?: string;
  customErrorTemplate?: string;
}

/** model/RouteAuthBindingEntity — binding rows returned by /api/auth/bindings. */
export interface RouteAuthBinding {
  /** Auto-increment DB id. */
  id?: number;
  /** Gateway instance UUID; used for client-side filtering (the list
   *  endpoint returns bindings of ALL instances). */
  instanceId?: string;
  /** UUID, unique identifier used by the binding endpoints. */
  bindingId: string;
  policyId: string;
  routeId: string;
  /** Backend default 100. */
  priority?: number;
  /** Backend default true. */
  enabled?: boolean;
  createdAt?: string;
}

/** POST /api/auth/bindings request body (controller reads a raw Map). */
export interface CreateBindingRequest {
  policyId: string;
  routeId: string;
  /** Optional; backend defaults to 100 when absent. */
  priority?: number;
}

/** POST /api/auth/bindings/batch request body (controller reads a raw Map). */
export interface BatchBindRequest {
  routeId: string;
  policyIds: string[];
}

/** GET /api/auth/policies/{policyId}/bindings/count response. */
export interface BindingCount {
  policyId: string;
  bindingCount: number;
}

/**
 * GET /api/auth/policies/{policyId}/usage-example response.
 * Backend returns a Map<String, Object> whose keys vary by auth type;
 * known keys are listed here (see AuthPolicyService.generateUsageExample).
 */
export interface AuthUsageExample {
  authType?: string;
  error?: string;
  headerName?: string;
  headerValue?: string;
  curlExample?: string;
  tokenExpiresIn?: string;
  algorithm?: string;
  prefixNote?: string;
  credentialsFormat?: string;
  credentialsEncoded?: string;
  curlWithAuthFlag?: string;
  realm?: string;
  getTokenCurl?: string;
  clientId?: string;
  tokenEndpoint?: string;
  requiredScopes?: string;
  note?: string;
  requiredHeaders?: { name: string; value: string }[];
  signatureCalculation?: string;
  stringToSignFormat?: string;
  signatureAlgorithm?: string;
  accessKey?: string;
}
