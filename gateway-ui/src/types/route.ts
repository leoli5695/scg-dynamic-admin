/**
 * Route domain types.
 *
 * Field-aligned with backend sources of truth:
 * - model/RouteDefinition.java (create/update request bodies)
 * - model/RouteResponse.java (GET list / GET by id responses)
 * - model/RouteServiceBinding.java (JSON field for the service type is
 *   serialized as "type" via @JsonProperty; accepts alias "serviceType")
 * - model/GrayRules.java + model/ServiceType.java
 */

/** model/RouteDefinition.RoutingMode */
export type RoutingMode = 'SINGLE' | 'MULTI';

/**
 * model/ServiceType enum values (serialized by name via @JsonValue).
 * DISCOVERY is a backend alias for NACOS kept for backward compatibility.
 */
export type ServiceBindingType = 'STATIC' | 'NACOS' | 'CONSUL' | 'DISCOVERY';

/** GrayRules.RuleType */
export type GrayRuleType = 'HEADER' | 'COOKIE' | 'QUERY' | 'WEIGHT';

/** RouteDefinition.PredicateDefinition — args is Map<String, String>. */
export interface RoutePredicate {
  name: string;
  args?: Record<string, string>;
}

/** RouteDefinition.FilterDefinition — args is Map<String, String>. */
export interface RouteFilter {
  name: string;
  args?: Record<string, string>;
}

/** GrayRules.GrayRule — value is always a string (WEIGHT stores percent). */
export interface GrayRule {
  type: GrayRuleType;
  /** Header/cookie/query parameter name; unused for WEIGHT. */
  name?: string;
  value: string;
  /** Target serviceId to route to when the rule matches. */
  targetVersion: string;
  description?: string;
}

/** model/GrayRules */
export interface GrayRules {
  enabled: boolean;
  rules: GrayRule[];
}

/** model/RouteServiceBinding */
export interface RouteServiceBinding {
  /** JSON field name is "type" (backend @JsonProperty); alias "serviceType". */
  type?: ServiceBindingType;
  /** STATIC: service UUID; NACOS/CONSUL: registered service name. */
  serviceId: string;
  serviceName?: string;
  /** 1-100, backend default 100. */
  weight: number;
  version?: string;
  enabled: boolean;
  description?: string;
  /** NACOS only; null means the gateway's own namespace. */
  serviceNamespace?: string;
  /** NACOS only; defaults to DEFAULT_GROUP. */
  serviceGroup?: string;
}

/** Route/service category discriminator. */
export type RouteCategory = 'NORMAL' | 'AI';

/** model/AiUpstream — binds an AI route to one AI service (LLM provider). */
export interface AiUpstream {
  /** AI service name (the bound LLM provider service). */
  provider: string;
  /** Weight for multi-upstream load balancing (1-100). */
  weight?: number;
  /** Requested model -> upstream model rewrites for this upstream. */
  modelMapping?: Record<string, string>;
}

/** model/AiModelPredicate — EXACT or PREFIX match on the requested model (no regex). */
export interface AiModelPredicate {
  matchType?: 'EXACT' | 'PREFIX';
  value: string;
}

/** model/AiRouteFallbackConfig — ordered failover across AI upstreams. */
export interface AiRouteFallbackConfig {
  enabled?: boolean;
  upstreams?: AiUpstream[];
  fallbackStrategy?: 'SEQ' | 'RANDOM';
}

/**
 * model/RouteDefinition — POST /api/routes and PUT /api/routes/{id} bodies.
 * Note: the backend model has no "enabled" field; enable/disable is done
 * through the dedicated /enable and /disable endpoints.
 */
export interface RouteDefinition {
  /** UUID; generated by the backend on create, path param on update. */
  id?: string;
  routeName: string;
  order?: number;
  /** UI-only (transient on the backend, not pushed to Nacos). */
  description?: string;
  /** Single-service target, e.g. "lb://user-service" or "static://uuid". */
  uri?: string;
  mode?: RoutingMode;
  /** Pure service name for SINGLE mode (extracted from uri). */
  serviceId?: string;
  serviceNamespace?: string;
  serviceGroup?: string;
  services?: RouteServiceBinding[];
  grayRules?: GrayRules;
  predicates?: RoutePredicate[];
  filters?: RouteFilter[];
  metadata?: Record<string, unknown>;
  /** NORMAL (default) or AI. AI routes bind AI services only. */
  category?: RouteCategory;
  /** AI routes: bound AI services with weight + model mapping. */
  aiUpstreams?: AiUpstream[];
  /** AI routes: model match predicates. */
  modelPredicates?: AiModelPredicate[];
  /** AI routes: fallback across upstreams. */
  aiFallback?: AiRouteFallbackConfig;
}

/** model/RouteResponse — what GET endpoints return. */
export interface RouteResponse {
  id: string;
  routeName?: string;
  uri?: string;
  mode?: RoutingMode;
  serviceId?: string;
  serviceNamespace?: string;
  serviceGroup?: string;
  services?: RouteServiceBinding[];
  grayRules?: GrayRules;
  order?: number;
  predicates?: RoutePredicate[];
  filters?: RouteFilter[];
  metadata?: Record<string, unknown>;
  enabled?: boolean;
  description?: string;
  category?: RouteCategory;
  aiUpstreams?: AiUpstream[];
  modelPredicates?: AiModelPredicate[];
  aiFallback?: AiRouteFallbackConfig;
}
